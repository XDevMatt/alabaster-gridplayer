"""Generate docs/reference/hotkeys.md from the default keymap.

The default shortcuts are the "key" / "keys" entries of ACTIONS in
gridplayer/params/actions.py. The file is read with ast, so neither PyQt
nor the app has to be importable.

    python tools/gen_hotkeys_md.py
"""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "gridplayer" / "params" / "actions.py"
TARGET = ROOT / "docs" / "reference" / "hotkeys.md"


def _text(node):
    """The plain text of a title: string constants, translate(ctx, "x"),
    and + of those. Anything else gives None."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "translate":
        return _text(node.args[1])
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _text(node.left), _text(node.right)
        if left is not None and right is not None:
            return left + right
    return None


def _actions_dict(tree):
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Assign)
            and any(getattr(t, "id", "") == "ACTIONS" for t in node.targets)
            and isinstance(node.value, ast.Call)
        ):
            return node.value.args[0]
    raise SystemExit("ACTIONS not found in " + str(SOURCE))


def collect():
    rows = []
    actions = _actions_dict(ast.parse(SOURCE.read_text(encoding="utf-8")))
    for key_node, value in zip(actions.keys, actions.values):
        if not isinstance(value, ast.Dict):
            continue
        fields = {
            k.value: v for k, v in zip(value.keys, value.values)
            if isinstance(k, ast.Constant)
        }
        keys = []
        if "key" in fields:
            keys = [ast.literal_eval(fields["key"])]
        elif "keys" in fields:
            keys = list(ast.literal_eval(fields["keys"]))
        if not keys:
            continue
        name = key_node.value
        title = _text(fields["title"]) if "title" in fields else None
        rows.append((title or name, name, keys))
    return rows


def _cell(text):
    return "`" + text.replace("|", "\\|") + "`" if text else ""


def render(rows):
    out = [
        "# Hotkeys",
        "",
        "<!-- Generated by tools/gen_hotkeys_md.py from"
        " gridplayer/params/actions.py. Do not edit by hand. -->",
        "",
        "These are the default shortcuts. They can be changed in Settings, on the"
        " Shortcuts page (also opened by Shortcuts on the right-click menu). Mouse entries such as `Click` or"
        " `Wheel` are mouse gestures from the same keymap.",
        "",
        f"{len(rows)} actions have a default shortcut.",
        "",
        "| Action | Internal name | Default keys |",
        "| --- | --- | --- |",
    ]
    for title, name, keys in rows:
        safe_title = title.replace("|", "\\|")
        out.append(
            f"| {safe_title} | {_cell(name)} | "
            + ", ".join(_cell(k) for k in keys)
            + " |"
        )
    return "\n".join(out) + "\n"


def main():
    rows = collect()
    TARGET.write_text(render(rows), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(rows)} rows")


if __name__ == "__main__":
    main()
